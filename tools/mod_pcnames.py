#!/usr/bin/env python3
"""Where the PC version's loose files sit inside the PS1 disc's archives.

The PC version (gun_bio, PSX_DATA folder) keeps the rooms, doors and
effects as loose files that are byte for byte the ones packed in the PS1
disc's archives (B/STGBGn.BIN, B/DOORANM.BIN, EFFECTX.BIN). This finds
each one and writes port/src/modfs_pc.h, so a mod made for the PC version
(port/src/modfs.c) can be dropped in as it is.

Usage: mod_pcnames.py <PSX_DATA folder> <disc .cue/.bin> [out.h]
Only files found whole and in one place are listed; the rest (enemies,
items, 2D, sound, movies) are in other formats on the PS1 disc.
"""
import os
import re
import sys
import zlib

here = os.path.dirname(os.path.abspath(__file__))


def disc_files():
    src = open(os.path.join(here, '..', 'port', 'src', 'disc_ids.h')).read()
    return [(n, int(l), int(s), int(h, 16)) for n, l, s, h in re.findall(r'\{"([^"]+)", (\d+)u, (\d+)u, 0x([0-9A-F]+)ull\}', src)]


def read_file(binf, lba, size):
    out = bytearray()
    for s in range((size + 2047) // 2048):
        binf.seek((lba + s) * 2352 + 24)
        out += binf.read(2048)
    return bytes(out[:size])


def main():
    pc, disc = sys.argv[1], sys.argv[2]
    out_h = sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, '..', 'port', 'src', 'modfs_pc.h')
    if disc.lower().endswith('.cue'):
        disc = os.path.join(os.path.dirname(disc), re.search(r'FILE "([^"]+)"', open(disc).read()).group(1))
    binf = open(disc, 'rb')
    # archives only: the files that hold no game code and aren't streamed (STR)
    arch = {n: read_file(binf, l, s) for n, l, s, h in disc_files() if h == 0 and not n.endswith('.STR') and s > 2048}
    rows = []
    for root, _, files in os.walk(pc):
        for fn in files:
            p = os.path.join(root, fn)
            data = open(p, 'rb').read()
            if len(data) < 64:
                continue
            hits = [(n, b.find(data)) for n, b in arch.items() if b.find(data) >= 0]
            if len(hits) != 1 or arch[hits[0][0]].find(data, hits[0][1] + 1) >= 0:
                continue                                  # not there, or not in one place
            rel = os.path.relpath(p, pc).replace(os.sep, '/')
            rows.append((rel.upper(), hits[0][0], hits[0][1], len(data), zlib.crc32(data) & 0xFFFFFFFF))
    rows.sort()
    with open(out_h, 'w', newline='\n') as f:
        f.write('/* Generated by tools/mod_pcnames.py: the PC version\'s loose files (PSX_DATA,\n'
                ' * upper case) found byte for byte inside the PS1 disc\'s files: disc file,\n'
                ' * byte offset, size, CRC-32 of the original. See modfs.c. */\n')
        f.write('static const struct { const char *pc, *disc; uint32_t offset, size, crc; } modfs_pc[] = {\n')
        for r in rows:
            f.write('    {"%s", "%s", %du, %du, 0x%08Xu},\n' % r)
        f.write('};\n')
    print('%d PC files placed, written to %s' % (len(rows), out_h))


if __name__ == '__main__':
    main()
