#!/usr/bin/env python3
"""Turn ld.lld "undefined symbol" errors into address definitions.

splat names every symbol after its address (`func_800F34E4`,
`D_800F51F0_ovl15`), so an undefined one can be placed exactly where its name
says.  This happens where a code/data boundary guess left an address without
a label; defining it by address keeps the rebuild byte-identical until the
boundary is fixed properly.

Reads linker output on stdin, writes `name = 0xADDR;` lines to the given file.
Exits non-zero if a symbol's name carries no address.

Usage: ld.lld ... 2>&1 | gen_undef_syms.py <out.txt>
"""
import re
import sys

NAME = re.compile(r"undefined symbol: (\S+)")
# `func_X`, `D_X`, `jtbl_X`, or a local label `.LX`, each with an optional
# `_<segment>` suffix.
ADDR = re.compile(r"^(?:(?:func|D|jtbl)_|\.L)([0-9A-F]{8})(?:_\w+)?$")

names = sorted(set(NAME.findall(sys.stdin.read())))
lines, bad = [], []
for n in names:
    m = ADDR.match(n)
    if m:
        # Quoted so names starting with "." are valid in an lld script.
        lines.append(f'"{n}" = 0x{m.group(1)};')
    else:
        bad.append(n)
with open(sys.argv[1], "w") as f:
    f.write("/* Generated by tools/gen_undef_syms.py from linker errors. */\n")
    f.write("\n".join(lines) + "\n")
print(f"{sys.argv[1]}: placed {len(lines)} symbols by address")
if bad:
    sys.exit(f"cannot place (no address in name): {bad}")
