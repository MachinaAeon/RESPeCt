#!/usr/bin/env python3
"""What the port checks a player's disc image against (port/src/disc_ids.h):
every file's position and size on the USA disc, and a hash of each file
that holds game code (the release build runs that code from the disc, so
it must be exactly the code its tables were made from). Numbers only.

Usage: disc_ids.py [disc image]   (default disc/image/survivor.bin)"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE = {"KERNEL.BIN", "TEST.BIN", "TITLE.BIN", "TYPEW.BIN", "SCORE.BIN", "STAFF.BIN", "OPTION.BIN",
        "DEBUG.BIN", "ENEMPROG.BIN", "STAGPROG.BIN", "CONPAU.BIN", "SLUS_010.87", "SYSTEM.CNF"}


def fnv64(b):
    h = 0xCBF29CE484222325
    for x in b:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "disc/image/survivor.bin")
    f = open(path, "rb")

    def sector(lba):
        f.seek(lba * 2352)
        return f.read(2352)[24:24 + 2048]

    def read(lba, size):
        return b"".join(sector(lba + i) for i in range((size + 2047) // 2048))[:size]

    pvd = sector(16)
    assert pvd[1:6] == b"CD001"
    out = []

    def walk(lba, size, prefix):
        for s in range((size + 2047) // 2048):
            d = sector(lba + s)
            o = 0
            while o < 2048 and d[o]:
                ln = d[o]
                flba, fsize = struct.unpack_from("<I", d, o + 2)[0], struct.unpack_from("<I", d, o + 10)[0]
                flags, nlen = d[o + 25], d[o + 32]
                name = d[o + 33:o + 33 + nlen]
                o += ln
                if name in (b"\0", b"\1"):
                    continue
                name = name.decode().split(";")[0]
                if flags & 2:
                    walk(flba, fsize, prefix + name + "/")
                else:
                    h = fnv64(read(flba, fsize)) if prefix + name in CODE else 0
                    out.append((prefix + name, flba, fsize, h))

    root = pvd[156:156 + 34]
    walk(struct.unpack_from("<I", root, 2)[0], struct.unpack_from("<I", root, 10)[0], "")
    f.seek(0, 2)
    sectors = f.tell() // 2352
    L = ["/* Generated by tools/disc_ids.py: the files of the Resident Evil Survivor",
         " * (USA) disc (SLUS-01087): name, first sector, size, and a hash of the",
         " * ones that hold game code (0: not checked). */",
         f"#define DISC_SECTORS {sectors}u",
         "static const struct { const char *name; uint32_t lba, size; uint64_t hash; } disc_files[] = {"]
    for name, lba, size, h in out:
        L.append(f'    {{"{name}", {lba}u, {size}u, 0x{h:016X}ull}},')
    L.append("};")
    open(os.path.join(ROOT, "port/src/disc_ids.h"), "w").write("\n".join(L) + "\n")
    print(f"{len(out)} files, {sum(1 for x in out if x[3])} hashed")


if __name__ == "__main__":
    main()
