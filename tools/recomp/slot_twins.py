#!/usr/bin/env python3
"""Generate the decompiled enemy programs for their other load slot.

Every enemy program is on the disc twice (ENEMPROG): built for enemy slot
B (0x80100000, overlays 49-64) and for slot A (0x800F8000, overlays
33-48). The two builds are the same code, relocated by 0x8000 (checked:
every differing word is a relocated address, jump or hi/lo half). So a
program decompiled for one slot gives the other slot's by shifting the
addresses inside the overlay's range.

For each port/decomp file that defines natives of an enemy overlay, this
writes port/decomp/twin_<file>.c: the file with those addresses shifted
and its n_ functions renamed (_A or _B), and lists them in the generated
block at the end of tools/recomp/native.txt. Run it after changing an
enemy file (then recomp.py and meta.py as usual).
"""
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NATIVE = os.path.join(ROOT, "tools/recomp/native.txt")
DECOMP = os.path.join(ROOT, "port/decomp")
MARK = "# ---- generated by tools/recomp/slot_twins.py (enemy programs, other slot) ----"

SLOT_A, SLOT_B, SIZE = 0x800F8000, 0x80100000, 0x8000


def twin_of(module):
    """(twin module, address shift, suffix) for an enemy overlay, else None."""
    m = re.fullmatch(r"ovl(\d+)", module)
    if not m:
        return None
    oid = int(m.group(1))
    if 49 <= oid <= 64:
        return f"ovl{oid - 16}", -SIZE, "_A"
    if 33 <= oid <= 48:
        return f"ovl{oid + 16}", SIZE, "_B"
    return None


def main():
    lines = open(NATIVE).read().split("\n")
    if MARK in lines:
        lines = lines[:lines.index(MARK)]
        while lines and lines[-1] == "":
            lines.pop()
    entries = [l.split() for l in lines if l.strip() and not l.startswith("#")]
    have = {(e[0], e[1].upper()) for e in entries}

    defined = {}
    for f in sorted(os.listdir(DECOMP)):
        if f.endswith(".c") and not f.startswith("twin_"):
            for n in re.findall(r"^void n_(\w+)\(void\)\s*\{", open(os.path.join(DECOMP, f)).read(), re.M):
                defined[n] = f

    jobs = defaultdict(list)          # (file, shift, suffix) -> [(twin module, twin addr, name)]
    for mod, addr, name in (e[:3] for e in entries if len(e) == 3 and not e[2].startswith("~")):
        t = twin_of(mod)
        if not t or name not in defined:
            continue
        tmod, shift, suffix = t
        taddr = f"{int(addr, 16) + shift:08X}"
        if (tmod, taddr) in have:
            continue                  # the other slot's copy is decompiled on its own
        jobs[(defined[name], shift, suffix)].append((tmod, taddr, name))

    for f in os.listdir(DECOMP):
        if f.startswith("twin_"):
            os.remove(os.path.join(DECOMP, f))
    out = ["", MARK]
    for (f, shift, suffix), items in sorted(jobs.items()):
        src = open(os.path.join(DECOMP, f)).read()
        lo, hi = (SLOT_B, SLOT_B + SIZE) if shift < 0 else (SLOT_A, SLOT_A + SIZE)

        def reloc(m):
            v = int(m.group(1), 16)
            if lo <= v < hi:
                return f"0x{v + shift:08X}"
            return m.group(0)
        src = re.sub(r"\b0x([0-9A-Fa-f]{8})(?![0-9A-Fa-f])", reloc, src)
        names = set(re.findall(r"^void n_(\w+)\(void\)", src, re.M))
        src = re.sub(r"\bn_(\w+)\b", lambda m: f"n_{m.group(1)}{suffix}" if m.group(1) in names else m.group(0), src)
        slot = "A (0x800F8000)" if suffix == "_A" else "B (0x80100000)"
        head = (f"/* GENERATED by tools/recomp/slot_twins.py from {f}: the same program\n"
                f" * built for enemy slot {slot}, addresses inside the overlay shifted by\n"
                f" * {shift:+#x}. Edit {f}, not this file. */\n")
        name = f"twin_{f[:-2]}{suffix.lower()}.c"
        open(os.path.join(DECOMP, name), "w").write(head + src)
        out.append(f"# {name}")
        for tmod, taddr, n in sorted(items, key=lambda x: (x[0], x[1])):
            out.append(f"{tmod:9s} {taddr}  {n}{suffix}")
    open(NATIVE, "w").write("\n".join(lines + out) + "\n")
    print(f"{sum(len(v) for v in jobs.values())} twin natives in {len(jobs)} files")


if __name__ == "__main__":
    sys.exit(main())
