#!/usr/bin/env python3
"""Write build/mods/SLUS-01087.cht: every test patch for DuckStation.

Each entry lists (original, modified) file pairs; the changed 16-bit values
become GameShark codes:

  kernel  KERNEL.BIN is always in memory from boot, so writes are unguarded:
              80AAAAAA VVVV
  slot0   overlays loaded at 0x8006C118 (TEST, TITLE, ...) share that slot, so
          each write is guarded on the file's first word (unique per overlay):
              D006C118 GGGG
              80AAAAAA VVVV

DuckStation applies a patch every frame (Activation = EndFrame), so a
reloaded file gets its patch back on the next frame.

Usage: make_patches.py      (after tools/build_mod.py)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "build/mods/SLUS-01087.cht")
SLOT0 = 0x8006C118
KERNEL_RAM = 0x80010000 - 0x800       # file offset -> RAM (PS-X EXE header is 0x800)

ENTRIES = [
    ("Test: double walk speed",
     "Mechanism check for the PC port project. Walking (not running) is twice as fast.",
     [("disc/TEST.BIN", "build/mods/TEST_walk2x.BIN", "slot0")]),
    ("FPS prototype (keyboard pad port 1, mouse port 2)",
     "C player controls plus the FPS prototype. Port 1 digital pad bound to the keyboard, "
     "port 2 PlayStation Mouse: mouse look (both axes), left click fires while moving, W/S move, A/D strafe, Cross (left Shift) sprints "
     "(mouse read directly from port 2). "
     "Without a mouse in port 2 it plays like the original.",
     [("disc/KERNEL.BIN", "build/mods/KERNEL_mod.BIN", "kernel"),
      ("disc/TEST.BIN", "build/mods/TEST_mod.BIN", "slot0")]),
]


# FPS settings block (include/c/game.h PortConfig) for the emulator: heading
# and pitch units per mouse count, pitch limit (4096 = 360), flags.
FPS_CONFIG = 0x80011288
extra_writes = {
    "FPS prototype (keyboard pad port 1, mouse port 2)": [
        (FPS_CONFIG + 0, 0x5043), (FPS_CONFIG + 2, 0x5253),
        (FPS_CONFIG + 4, 2), (FPS_CONFIG + 6, 2), (FPS_CONFIG + 8, 0x300), (FPS_CONFIG + 10, 0)],
}


def writes(orig, mod, kind):
    a = open(os.path.join(ROOT, orig), "rb").read()
    b = open(os.path.join(ROOT, mod), "rb").read()
    if len(a) != len(b):
        sys.exit(f"{mod}: size differs from {orig}")
    if kind == "slot0":
        base, guard = SLOT0, int.from_bytes(a[0:2], "little")
        first = 4                      # never patch the guard word itself
    elif kind == "kernel":
        base, guard = KERNEL_RAM, None
        first = 0x800                  # the EXE header isn't loaded
    else:
        sys.exit(f"unknown kind {kind}")
    out = []
    for off in range(0, len(a) - 1, 2):
        if a[off:off + 2] != b[off:off + 2]:
            if off < first:
                sys.exit(f"{mod}: change at {off:#x} is outside the patchable range")
            out.append((guard, base + off, int.from_bytes(b[off:off + 2], "little")))
    return out


def main():
    lines = ["# Resident Evil Survivor (USA) [SLUS-01087]",
             "# Test patches from the PC port project. Generated by tools/make_patches.py.", ""]
    for name, desc, parts in ENTRIES:
        lines += [f"[{name}]", "Type = Gameshark", "Activation = EndFrame",
                  "Author = Resident Evil Survivor PC port project",
                  f"Description = {desc}", ""]
        count = 0
        for orig, mod, kind in parts:
            for guard, addr, val in writes(orig, mod, kind):
                if guard is not None:
                    lines.append(f"D0{SLOT0 & 0xFFFFFF:06X} {guard:04X}")
                lines.append(f"80{addr & 0xFFFFFF:06X} {val:04X}")
                count += 1
        for addr, val in extra_writes.get(name, []):
            lines.append(f"80{addr & 0xFFFFFF:06X} {val:04X}")
            count += 1
        lines.append("")
        print(f"{name}: {count} writes")
    open(OUT, "w", encoding="ascii").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
